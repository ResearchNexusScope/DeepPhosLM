#!/usr/bin/env python3
"""True bin-level reliability diagram from saved prediction NPZ archives.

E-004/E-005 persist ECE scalars, not reliability bin points, so the existing
``calibration_ece.png`` is a summary rather than a reliability curve.  This CLI
recomputes the bin points directly from the archived labels/probabilities with
:func:`src.statistics.calibration_bins` and writes:

* ``<results-dir>/calibration_bins.json`` -- per-ablation and pooled bin points
  with per-file provenance (path, SHA-256, seed, n);
* ``<out-dir>/reliability_diagram.png`` -- a bin-level empirical reliability
  diagram (mean predicted probability vs observed positive fraction, one point
  per occupied equal-width bin, marker size proportional to bin count);
* ``<out-dir>/reliability_manifest.json`` -- hash-pinned manifest of the input
  NPZs, the bins JSON and the rendered PNG.

Usage (from the repository root)::

    python tools/plot_reliability.py \
        --predictions "results/real/predictions_*.npz" \
        --results-dir results/real \
        --out-dir figures/real

``--predictions`` accepts either a directory of ``*.npz`` files or a glob
pattern.  No number is hardcoded: all bin points, counts, ECE values and
hashes are computed at run time from the files actually passed in.  No
simulated data is generated by this tool.

Honest caption (also embedded in the PNG and manifest): bin-level empirical
reliability, equal-width bins in [0, 1], finite-sample noise -- sparse bins are
unstable; ECE is computed from these bin points and no smoothing is applied.
"""
from __future__ import annotations

import argparse
import glob
import hashlib
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Mapping, Sequence

import matplotlib

matplotlib.use("Agg")  # headless batch figure generator
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.statistics import (  # noqa: E402
    CALIBRATION_CAVEATS,
    CALIBRATION_METHOD,
    DEFAULT_N_BINS,
    DEFAULT_SEED,
    calibration_bins,
)

FIGURE_DPI = 200
BINS_FILENAME = "calibration_bins.json"
FIGURE_FILENAME = "reliability_diagram.png"
MANIFEST_FILENAME = "reliability_manifest.json"

CAPTION = (
    "Bin-level empirical reliability: equal-width bins in [0, 1]; finite-sample "
    "noise (sparse bins are unstable). ECE is computed from these bin points; "
    "no smoothing or inferential interval is applied."
)

STATEMENT = (
    "Every bin point, ECE value and hash is computed at run time from the NPZ "
    "archives listed under 'inputs'. This tool generates no simulated data and "
    "types no reported result value."
)

SEED_NOTE = (
    "calibration is deterministic and performs no resampling; the tool seed is "
    "recorded for provenance parity with the bootstrap tools, and each NPZ's "
    "own seed is recorded per file"
)

POOLED_NOTE = (
    "each seed/ablation scores the same test rows, so the pooled group repeats "
    "those rows across archives; it is a descriptive average, not an independent sample"
)


# --------------------------------------------------------------------------- #
# Provenance / loading
# --------------------------------------------------------------------------- #
def sha256_file(path: Path) -> str:
    """SHA-256 of a file, streamed so large NPZs stay cheap."""
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def discover_npz(predictions: str) -> List[Path]:
    """Resolve ``--predictions`` as a directory of NPZs or a glob pattern."""
    candidate = Path(str(predictions))
    if candidate.is_dir():
        files = sorted(candidate.glob("*.npz"))
    else:
        files = [
            Path(match)
            for match in sorted(glob.glob(str(predictions), recursive=True))
            if Path(match).is_file() and Path(match).suffix.lower() == ".npz"
        ]
    files = sorted(set(files))
    if not files:
        raise FileNotFoundError(f"no .npz prediction archives matched: {predictions!r}")
    for path in files:
        if not path.is_file():
            raise FileNotFoundError(f"prediction archive is not a file: {path}")
    return files


def _scalar_text(value: Any) -> str:
    """Normalise a 0-D NPZ array/scalar to a plain string."""
    array = np.asarray(value)
    if array.ndim == 0:
        return str(array.item())
    if array.size == 0:
        raise ValueError("empty scalar field in NPZ")
    return str(array.reshape(-1)[0].item())


def _scalar_int(value: Any, field: str, path: Path) -> int:
    try:
        return int(np.asarray(value).item())
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{path}: {field} must be an integer scalar") from exc


def load_archive(path: Path) -> Dict[str, Any]:
    """Read labels/probabilities/ablation/seed from one prediction NPZ."""
    try:
        with np.load(path, allow_pickle=False) as data:
            missing = [key for key in ("labels", "probabilities", "ablation", "seed") if key not in data.files]
            if missing:
                raise ValueError(f"{path} is missing NPZ keys: {missing}")
            labels = np.asarray(data["labels"]).ravel().astype(np.int64)
            probabilities = np.asarray(data["probabilities"], dtype=np.float64).ravel()
            ablation = _scalar_text(data["ablation"])
            seed = _scalar_int(data["seed"], "seed", path)
    except (ValueError, OSError, EOFError, TypeError) as exc:
        raise ValueError(
            f"{path}: could not load prediction archive with allow_pickle=False; "
            "expected plain numeric/string arrays, not pickled object arrays. "
            f"Original error: {exc}"
        ) from exc
    if labels.size != probabilities.size:
        raise ValueError(f"{path}: label/probability length mismatch")
    if labels.size == 0:
        raise ValueError(f"{path}: empty prediction archive")
    if not np.all(np.isfinite(probabilities)) or np.any(probabilities < 0) or np.any(probabilities > 1):
        raise ValueError(f"{path}: probabilities must be finite and inside [0, 1]")
    return {
        "path": path,
        "labels": labels,
        "probabilities": probabilities,
        "ablation": ablation,
        "seed": seed,
        "n": int(labels.size),
        "sha256": sha256_file(path),
    }


# --------------------------------------------------------------------------- #
# Bin points and JSON
# --------------------------------------------------------------------------- #
def build_bins_payload(
    archives: Sequence[Mapping[str, Any]], n_bins: int = DEFAULT_N_BINS, seed: int = DEFAULT_SEED
) -> Dict[str, Any]:
    """Compute calibration bins per ablation and pooled, with provenance."""
    grouped: Dict[str, List[Mapping[str, Any]]] = {}
    for archive in archives:
        grouped.setdefault(str(archive["ablation"]), []).append(archive)

    groups: Dict[str, Any] = {}
    for ablation in sorted(grouped):
        members = grouped[ablation]
        labels = np.concatenate([np.asarray(item["labels"]) for item in members])
        probabilities = np.concatenate([np.asarray(item["probabilities"]) for item in members])
        result = calibration_bins(labels, probabilities, n_bins=n_bins)
        result["provenance"] = {
            "files": [
                {
                    "path": str(item["path"]),
                    "sha256": item["sha256"],
                    "seed": int(item["seed"]),
                    "n": int(item["n"]),
                    "ablation": str(item["ablation"]),
                }
                for item in members
            ],
            "pooling": "all seeds of this ablation concatenated (identical test rows repeated)",
        }
        groups[ablation] = result

    all_labels = np.concatenate([np.asarray(item["labels"]) for item in archives])
    all_probabilities = np.concatenate([np.asarray(item["probabilities"]) for item in archives])
    pooled = calibration_bins(all_labels, all_probabilities, n_bins=n_bins)
    pooled["provenance"] = {
        "files": [
            {
                "path": str(item["path"]),
                "sha256": item["sha256"],
                "seed": int(item["seed"]),
                "n": int(item["n"]),
                "ablation": str(item["ablation"]),
            }
            for item in archives
        ],
        "pooling": POOLED_NOTE,
    }
    groups["pooled"] = pooled

    return {
        "n_bins": int(n_bins),
        "seed": int(seed),
        "seed_note": SEED_NOTE,
        "method": CALIBRATION_METHOD,
        "caveats": list(CALIBRATION_CAVEATS),
        "caption": CAPTION,
        "groups": groups,
        "provenance": {
            "files": [
                {
                    "path": str(item["path"]),
                    "sha256": item["sha256"],
                    "seed": int(item["seed"]),
                    "n": int(item["n"]),
                    "ablation": str(item["ablation"]),
                }
                for item in archives
            ],
            "n_files": len(archives),
            "n_rows_summed_over_files": int(sum(item["n"] for item in archives)),
            "statement": STATEMENT,
        },
    }


# --------------------------------------------------------------------------- #
# Figure and manifest
# --------------------------------------------------------------------------- #
def plot_reliability(payload: Dict[str, Any], out_path: Path) -> Path:
    """Render occupied reliability bin points for every group, plus the diagonal."""
    out_path = Path(out_path)
    groups = payload["groups"]
    colors = plt.get_cmap("tab10")
    fig, ax = plt.subplots(figsize=(7.2, 6.2))
    ax.plot([0.0, 1.0], [0.0, 1.0], "k--", lw=1, label="perfect reliability")

    for index, name in enumerate(["pooled", *sorted(k for k in groups if k != "pooled")]):
        block = groups[name]
        points = [
            (entry["mean_pred"], entry["observed_fraction"], entry["n"])
            for entry in block["bins"]
            if entry["n"] > 0
        ]
        if not points:
            continue
        x = [point[0] for point in points]
        y = [point[1] for point in points]
        sizes = [18.0 + 6.0 * np.sqrt(point[2]) for point in points]
        ece_text = "undefined" if block["ece"] is None else f"{float(block['ece']):.4f}"
        ax.plot(x, y, color=colors(index % 10), lw=1.4, alpha=0.75)
        ax.scatter(
            x, y, s=sizes, color=colors(index % 10), edgecolors="black", linewidths=0.5,
            label=f"{name} (ECE={ece_text}, n={block['n']}, occupied={len(points)})",
            zorder=3,
        )

    ax.set_xlim(0.0, 1.0)
    ax.set_ylim(0.0, 1.0)
    ax.set_xlabel("Mean predicted probability in bin")
    ax.set_ylabel("Observed fraction of positives in bin")
    ax.set_title("Bin-level empirical reliability (equal-width bins, no smoothing)")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8, loc="upper left")
    fig.text(0.5, 0.01, CAPTION, ha="center", fontsize=8)
    fig.tight_layout(rect=(0, 0.055, 1, 1))
    fig.savefig(out_path, dpi=FIGURE_DPI, bbox_inches="tight")
    plt.close(fig)
    return out_path


def write_manifest(
    payload: Dict[str, Any],
    npz_paths: Sequence[Path],
    bins_path: Path,
    figure_path: Path,
    out_dir: Path,
) -> Path:
    """Pin hashes of every input NPZ, the bins JSON and the rendered figure."""
    inputs: Dict[str, Dict[str, Any]] = {}
    for path in npz_paths:
        inputs[str(path)] = {"sha256": sha256_file(path), "bytes": path.stat().st_size}
    inputs[str(bins_path)] = {
        "sha256": sha256_file(bins_path),
        "bytes": bins_path.stat().st_size,
        "role": "calibration_bins_json",
    }
    # Keep per-file seed/count alongside the hash-pinned file list.
    for entry in payload["provenance"]["files"]:
        inputs.setdefault(str(entry["path"]), {}).update(
            {"seed": int(entry["seed"]), "n": int(entry["n"]), "ablation": str(entry["ablation"])}
        )

    manifest = {
        "inputs": inputs,
        "outputs": {
            figure_path.name: {
                "sha256": sha256_file(figure_path),
                "bytes": figure_path.stat().st_size,
            }
        },
        "n_bins": int(payload["n_bins"]),
        "seed": int(payload["seed"]),
        "seed_note": SEED_NOTE,
        "dpi": FIGURE_DPI,
        "caption": CAPTION,
        "statement": STATEMENT,
        "method": CALIBRATION_METHOD,
        "caveats": list(CALIBRATION_CAVEATS),
        "groups": {
            name: {
                "n": int(block["n"]),
                "ece": block["ece"],
                "n_occupied": int(sum(1 for entry in block["bins"] if entry["n"] > 0)),
            }
            for name, block in payload["groups"].items()
        },
    }
    manifest_path = Path(out_dir) / MANIFEST_FILENAME
    manifest_path.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return manifest_path


def generate_all(
    predictions: str, results_dir: Path, out_dir: Path, n_bins: int = DEFAULT_N_BINS
) -> Dict[str, Any]:
    """Run the whole pipeline; return all paths and the bins payload."""
    npz_paths = discover_npz(predictions)
    archives = [load_archive(path) for path in npz_paths]
    payload = build_bins_payload(archives, n_bins=n_bins, seed=DEFAULT_SEED)

    results_dir = Path(results_dir)
    out_dir = Path(out_dir)
    results_dir.mkdir(parents=True, exist_ok=True)
    out_dir.mkdir(parents=True, exist_ok=True)

    bins_path = results_dir / BINS_FILENAME
    bins_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    figure_path = plot_reliability(payload, out_dir / FIGURE_FILENAME)
    manifest_path = write_manifest(payload, npz_paths, bins_path, figure_path, out_dir)
    return {
        "npz_paths": npz_paths,
        "bins": bins_path,
        "figure": figure_path,
        "manifest": manifest_path,
        "payload": payload,
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--predictions",
        default=str(REPO_ROOT / "results" / "real" / "predictions_*.npz"),
        help="directory of *.npz prediction archives, or a glob pattern matching them",
    )
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=REPO_ROOT / "results" / "real",
        help=f"destination for {BINS_FILENAME}",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=REPO_ROOT / "figures" / "real",
        help=f"destination for {FIGURE_FILENAME} and {MANIFEST_FILENAME}",
    )
    parser.add_argument(
        "--n-bins",
        type=int,
        default=DEFAULT_N_BINS,
        help="number of equal-width bins in [0, 1] (default: %(default)s)",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    result = generate_all(args.predictions, args.results_dir, args.out_dir, n_bins=args.n_bins)
    print(f"Wrote calibration bins, reliability figure and manifest from {len(result['npz_paths'])} NPZs")
    print(f"  bins:     {result['bins']}")
    print(f"  figure:   {result['figure']}")
    print(f"  manifest: {result['manifest']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
